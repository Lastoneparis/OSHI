    ) async -> [String] {
        #if canImport(FoundationModels)
        if #available(iOS 26, *), SystemLanguageModel.default.isAvailable {
            let deviceLang = Self.contentLanguageCode
            let langName = Locale.current.localizedString(forLanguageCode: deviceLang) ?? "the user's language"
            let name = recipientName ?? "the person"

            let contextBlock: String
            if let ctx = conversationContext, !ctx.isEmpty {
                contextBlock = """
                    CONVERSATION HISTORY — USE THIS TO PERSONALIZE EVERYTHING:
                    ---
                    \(String(ctx.prefix(800)))
                    ---
                    CRITICAL: Every suggestion MUST reference something specific from this conversation — a topic they discussed, \
                    an emotion they expressed, something they mentioned. Generic messages that could be sent to anyone are FORBIDDEN.
                    """
            } else {
                contextBlock = "No conversation history available. Generate creative, original openers that stand out from boring 'Hi how are you' messages."
            }

            let modeInstruction: String
            switch mode {
            case .icebreaker:
                modeInstruction = """
                    Generate 3 UNFORGETTABLE conversation starters for \(name). \
                    \
                    WHAT MAKES AN ICEBREAKER GREAT: \
                    - It's unexpected — not something they've heard 100 times before. \
                    - It invites a story, not a yes/no answer. \
                    - It reveals personality — you're interesting, not boring. \
                    \
                    THE 3 SUGGESTIONS: \
                    1. A FUN "WOULD YOU RATHER" OR SCENARIO: A creative hypothetical that sparks imagination. \
                       BAD: "What's your favorite movie?" → GOOD: "Ok random question — if you could relive one day of your life, which one would you pick?" \
                    2. AN OBSERVATION OR INSIGHT: Something clever that shows you pay attention to the world. \
                       BAD: "Nice weather today" → GOOD: "I just realized something — the people who say 'I hate mornings' are always the most fun at night" \
                    3. A BOLD, CURIOUS QUESTION: Direct and intriguing — makes them want to answer. \
                       BAD: "Tell me about yourself" → GOOD: "What's something about you that would surprise most people?"
                    """
            case .relaunch:
                modeInstruction = """
                    Generate 3 messages to REIGNITE a quiet conversation with \(name). \
                    \
                    GOLDEN RULE: Never sound desperate ("I miss talking to you", "Why didn't you reply?"). \
                    Instead, be magnetic — give them a REASON to respond. \
                    \
                    THE 3 SUGGESTIONS: \
                    1. THE CALLBACK: Reference something SPECIFIC from your conversation history and add a new angle. \
                       BAD: "Hey, it's been a while" → GOOD: "Remember when you told me about [that thing]? I just saw something that reminded me of it and I need to tell you" \
                    2. THE BAIT: Share something intriguing that naturally invites a response. A mini-story, a surprising fact, a funny situation. \
                       BAD: "What's new?" → GOOD: "You won't believe what just happened to me — I need someone to appreciate this properly" \
                    3. THE WARM CHECK-IN: Genuine caring without pressure. Show you thought about them specifically. \
                       BAD: "Hope you're doing well" → GOOD: "Random thought but I hope that [specific thing they mentioned] worked out — been lowkey wondering about it"
                    """
            case .flirty:
                modeInstruction = """
                    Generate 3 IRRESISTIBLY charming messages for \(name). \
                    \
                    THE ART OF FLIRTING IN TEXT: \
                    - Confidence, not arrogance. Playfulness, not crudeness. Specificity, not generic compliments. \
                    - The push-pull: compliment, then tease. Build tension, then release with humor. \
                    - Make THEM feel interesting, not just tell them they're attractive. \
                    \
                    THE 3 SUGGESTIONS: \
                    1. THE WITTY TEASE: A playful challenge or joke that shows confidence and humor. \
                       BAD: "You're cute" → GOOD: "I'm trying to figure out if you're actually this charming or if you're doing it on purpose..." \
                    2. THE SPECIFIC COMPLIMENT WITH A TWIST: Notice something unique, compliment it, then add intrigue. \
                       BAD: "You're pretty" → GOOD: "The way you [something specific from context]... I don't know why but I can't stop thinking about it" \
                    3. THE TENSION BUILDER: Create anticipation and curiosity. Make them wonder, imagine, lean in. \
                       BAD: "I like you" → GOOD: "I had something to tell you but I think it's the kind of thing that's better said in person... if you're brave enough 😏"
                    """
            case .friendly:
                modeInstruction = """
                    Generate 3 genuinely WARM messages for \(name) that strengthen the friendship. \
                    \
                    WHAT MAKES FRIENDLY MESSAGES GREAT: \
                    - They're specific, not generic. "I appreciate YOU for [specific reason]" beats "You're a great friend". \
                    - They create plans or shared experiences, not just pleasantries. \
                    - They make the person feel truly seen and valued. \
                    \
                    THE 3 SUGGESTIONS: \
                    1. THE GENUINE APPRECIATION: Acknowledge something specific about who they are or what they bring to your life. \
                       BAD: "You're the best!" → GOOD: "Honestly, talking to you always puts me in a better mood — you have this way of making everything feel lighter" \
                    2. THE PLAN MAKER: Suggest something fun and specific to do together. \
                       BAD: "We should hang out" → GOOD: "Ok I have an idea — we should [specific activity] this weekend. I'll bring the snacks, you bring the chaos" \
                    3. THE THOUGHTFUL QUESTION: Ask about something that shows you care about their inner world, not just small talk. \
                       BAD: "How are you?" → GOOD: "Hey, real talk — what's been the best part of your week so far?"
                    """
            }

            let session = LanguageModelSession(instructions: """
                You are a brilliant, emotionally intelligent communication coach who helps people craft PERFECT messages. \
                \(modeInstruction) \
                \(contextBlock) \
                \
                Write ALL suggestions in \(langName). Use natural texting style for this language. \
                Each suggestion: 1-3 sentences, sounds like a real human texting, NOT a robot or a greeting card. \
                Format: one suggestion per line, no numbering, no quotes, no explanation. \
                If a suggestion sounds like something you'd read in a template or a "100 conversation starters" blog post, DELETE it and write something original.
                """)

            do {
                let response = try await session.respond(to: "Generate the 3 suggestions now.")
                let lines = sanitizeLLMOutput(response.content)
                    .split(separator: "\n")
                    .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
                    .filter { !$0.isEmpty && !looksLikeMetaLine($0) }
                    .map { stripListBullet($0) }
                return Array(lines.prefix(3))
            } catch {
                return generateFallbackSuggestions(mode: mode)
            }
        }
        #endif
        // Local LLM fallback
        if LocalLLMManager.shared.isModelDownloaded {
            let recipientLabel = recipientName ?? "the person"
            let modeDesc: String
            switch mode {
            case .icebreaker: modeDesc = "creative conversation starters"
            case .relaunch: modeDesc = "messages to reignite a quiet conversation"
            case .flirty: modeDesc = "charming and flirty messages"
            case .friendly: modeDesc = "warm friendly messages"
            }
            var prompt = "Generate exactly 3 \(modeDesc) for \(recipientLabel). One per line. No numbering. Keep each to 1-2 sentences.\n\n"
            if let ctx = conversationContext, !ctx.isEmpty {
                prompt += "Conversation context:\n\(String(ctx.prefix(400)))\n\n"
            }
            prompt += "Generate the 3 suggestions now."
            let result = await LocalLLMManager.shared.generate(prompt: prompt)
            if !result.isEmpty && !result.contains("not yet linked") {
                let lines = result
                    .split(separator: "\n")
                    .map { String($0).trimmingCharacters(in: .whitespacesAndNewlines) }
                    .filter { !$0.isEmpty && $0.count > 5 }
                if lines.count >= 2 {
                    return Array(lines.prefix(3))
                }
            }
        }
        return generateFallbackSuggestions(mode: mode)
    }

