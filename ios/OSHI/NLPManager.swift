    // MARK: - Context-Aware Tone Suggestion

    /// Analyze a received message and suggest the best reply tone
    func suggestTone(forReplyTo message: String) -> ImprovementStyle {
        let sentiment = analyzeSentiment(message)
        let wordCount = message.split(separator: " ").count
        let hasExclamation = message.contains("!")
        let hasQuestion = message.contains("?")
        let isShort = wordCount < 8

        // Formal indicators: long sentences, no exclamation, neutral tone
        let formalWords = ["please", "kindly", "regarding", "sincerely", "respectfully",
                          "dear", "appreciate", "cordially", "furthermore"]
        let hasFormalWord = formalWords.contains(where: { message.lowercased().contains($0) })

        if hasFormalWord || (wordCount > 20 && sentiment.sentiment == .neutral) {
            return .professional
        }
        if sentiment.sentiment == .positive && hasExclamation {
            return .friendly
        }
        if isShort && (hasExclamation || hasQuestion) {
            return .casual
        }
        if sentiment.sentiment == .negative {
            return .friendly // soften response to negative messages
        }
        return .casual
    }

