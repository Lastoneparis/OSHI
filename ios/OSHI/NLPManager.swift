            return (result, true)
        }
        #endif
        // Local LLM fallback
        if LocalLLMManager.shared.isModelDownloaded {
            let toneDesc: String
            switch tone {
            case .romantic: toneDesc = "romantic and loving"
            case .friendly: toneDesc = "warm and friendly"
            case .family: toneDesc = "caring and familial"
            case .casual: toneDesc = "casual and relaxed"
            case .formal: toneDesc = "formal and respectful"
