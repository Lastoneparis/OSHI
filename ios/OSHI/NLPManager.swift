    /// Strip chain-of-thought / preamble that some on-device models leak despite "OUTPUT ONLY" instructions.
    /// Removes <think>…</think> blocks, leading meta-lines like "Okay, the user wants me to…", "Here's the rewrite:",
    /// "Sure, here is…", and surrounding quotes. Returns the actual rewritten message.
    private func sanitizeLLMOutput(_ raw: String) -> String {
        var s = raw

        // Strip <think>…</think> (some models echo their reasoning)
        if let openRange = s.range(of: "<think>", options: [.caseInsensitive]),
           let closeRange = s.range(of: "</think>", options: [.caseInsensitive], range: openRange.upperBound..<s.endIndex) {
            s.removeSubrange(openRange.lowerBound..<closeRange.upperBound)
        }
        s = s.replacingOccurrences(of: "<think>[\\s\\S]*?</think>", with: "", options: [.regularExpression, .caseInsensitive])

        // Strip ChatML tokens (`<|im_start|>`, `<|im_end|>`, `<|endoftext|>`, `<|user|>`,
        // `<|assistant|>`) and Apple Foundation Models leak markers without truncating the
        // answer. The previous "cut at first <|" approach destroyed every Qwen3 response
        // because Qwen3 echoes `<|im_start|>assistant` at the head of its output —
        // resulting in a permanently empty answer + "I couldn't generate" fallback.
        s = s.replacingOccurrences(of: "<\\|[^|>]{0,40}\\|>", with: "", options: .regularExpression)
        // Catch a stray opening `<|` followed by a token name without the closing `|>`
        // (rare, but Foundation Models occasionally emits one) — drop just the marker line.
        s = s.replacingOccurrences(of: "<\\|[a-zA-Z_]+\\b", with: "", options: .regularExpression)

        // If the model returned an HTML document, extract just the body's text content. The
        // user-visible bug was iOS Foundation Models occasionally wrapping a fact answer in
        // `<!DOCTYPE html><html><head>…</head><body><h1>…</h1><p>…</p></body></html>`.
        if s.range(of: "<!DOCTYPE", options: [.caseInsensitive]) != nil ||
           s.range(of: "<html", options: [.caseInsensitive]) != nil {
            // Prefer body content if present
            let lower = s.lowercased()
            if let bodyStart = lower.range(of: "<body"),
               let bodyOpenEnd = lower.range(of: ">", range: bodyStart.upperBound..<lower.endIndex),
               let bodyEnd = lower.range(of: "</body>", range: bodyOpenEnd.upperBound..<lower.endIndex) {
                let bodyRange = bodyOpenEnd.upperBound..<bodyEnd.lowerBound
                s = String(s[bodyRange])
            }
            // Strip any remaining HTML/XML tags
            s = s.replacingOccurrences(of: "<[^>]+>", with: "\n", options: .regularExpression)
            // Strip HTML entities we care about
            s = s.replacingOccurrences(of: "&amp;", with: "&")
                 .replacingOccurrences(of: "&lt;", with: "<")
                 .replacingOccurrences(of: "&gt;", with: ">")
                 .replacingOccurrences(of: "&quot;", with: "\"")
                 .replacingOccurrences(of: "&#39;", with: "'")
                 .replacingOccurrences(of: "&nbsp;", with: " ")
        }
        // Strip HTML comments (`<!-- Generated by AI -->` is a frequent leak)
        s = s.replacingOccurrences(of: "<!--[\\s\\S]*?-->", with: "", options: .regularExpression)

        // Strip a code-fence wrapper ```...``` if the model wrapped the message
        if let firstFence = s.range(of: "```"), let secondFence = s.range(of: "```", range: firstFence.upperBound..<s.endIndex) {
            let inside = s[firstFence.upperBound..<secondFence.lowerBound]
            // Drop optional language tag on the first line
            if let nl = inside.firstIndex(of: "\n") {
                s = String(inside[inside.index(after: nl)...])
            } else {
                s = String(inside)
            }
        }

        // Drop trailing boilerplate the model sometimes appends after the real answer.
        let trailingBoilerplate = [
            "I couldn't generate a response", "Please try again",
            "Please clarify your question", "rephrase it for better understanding",
            "I'm not able to", "I cannot answer", "Je ne peux pas",
        ]
        for marker in trailingBoilerplate {
            if let r = s.range(of: marker, options: [.caseInsensitive]) {
                s = String(s[..<r.lowerBound])
            }
        }

        // Collapse runs of blank lines and normalize whitespace
        s = s.replacingOccurrences(of: "\n\n\n+", with: "\n\n", options: .regularExpression)
             .replacingOccurrences(of: "[ \\t]+", with: " ", options: .regularExpression)

        s = s.trimmingCharacters(in: .whitespacesAndNewlines)

        // Drop leading meta-paragraphs ONLY when they are unambiguous chain-of-thought.
        // The previous list was way too aggressive — "okay,", "alright,", "let me", "first,",
        // "of course," are valid polite English answer openers and were eating the real answer.
        // Now we only strip the patterns that are explicitly model-side reasoning about the user
        // (Qwen3 / Foundation Models leak signature) or the rewrite-prefix style ("Here's the rewrite:").
        let metaLeads: [String] = [
            "the user wants", "the user is asking", "the user asked", "the user said",
            "let me think", "let me analyze", "let me break", "let me reason",
            "i need to figure", "i need to consider", "i should think",
            "here's the rewrite", "here's the rewritten", "here is the rewrite", "here is the rewritten",
            "here's the message", "here is the message",
            "here's the casual", "here's a casual", "here is the casual", "here is a casual",
            "here's the formal", "here is the formal",
            "here's the translation", "here is the translation",
            "here's the corrected", "here is the corrected",
            "voici la traduction", "voici le message", "voici votre",
            "ecco la traduzione", "ecco il messaggio",
            "aquí está la traducción", "aquí tienes el",
            "hier ist die übersetzung",
        ]
        // Iterate up to 3 times — sometimes the model emits multiple meta-paragraphs.
        for _ in 0..<3 {
            let lower = s.lowercased()
            let firstChunk = String(lower.prefix(80))
            guard metaLeads.contains(where: { firstChunk.hasPrefix($0) }) else { break }
            // Drop everything until the next double-newline (paragraph boundary) OR the first colon
            // followed by a newline ("Here's the rewrite:\n<actual message>").
            if let dblNL = s.range(of: "\n\n") {
                s = String(s[dblNL.upperBound...]).trimmingCharacters(in: .whitespacesAndNewlines)
            } else if let colonNL = s.range(of: ":\n") {
                s = String(s[colonNL.upperBound...]).trimmingCharacters(in: .whitespacesAndNewlines)
            } else if let nl = s.firstIndex(of: "\n") {
                s = String(s[s.index(after: nl)...]).trimmingCharacters(in: .whitespacesAndNewlines)
            } else {
                // Single line entirely meta — give up; leave original to avoid empty output
                break
            }
        }

        // Cut at the FIRST occurrence (anywhere, not just leading) of a mid-response
        // chain-of-thought marker. iOS Foundation Models occasionally appends a "Alright,
        // the user said …" reasoning block AFTER the real answer.
        let midResponseCutMarkers = [
            "\nAlright, the user", "\nOkay, the user", "\nThe user said",
            "Alright, the user said",
            "Please clarify your question", "I'll respond by", "Let me clarify",
        ]
        for marker in midResponseCutMarkers {
            if let r = s.range(of: marker) {
                s = String(s[..<r.lowerBound]).trimmingCharacters(in: .whitespacesAndNewlines)
            }
        }

        // Strip "Here's the X: " inline prefixes that survived the paragraph stripping
        let inlinePrefixes = [
            "Here's the rewrite:", "Here is the rewrite:",
            "Here's the rewritten message:", "Here is the rewritten message:",
            "Here's the corrected text:", "Here is the corrected text:",
            "Here's the translation:", "Here is the translation:",
            "Rewrite:", "Translation:", "Corrected:", "Output:",
            "Voici :", "Voici:", "Voici la traduction :", "Voici le message :",
        ]
        for p in inlinePrefixes {
            if s.lowercased().hasPrefix(p.lowercased()) {
                s = String(s.dropFirst(p.count)).trimmingCharacters(in: .whitespacesAndNewlines)
            }
        }

        // Strip wrapping quotes ("…" or “…” or « … »)
        let quotePairs: [(Character, Character)] = [("\"", "\""), ("'", "'"), ("\u{201C}", "\u{201D}"), ("\u{00AB}", "\u{00BB}")]
        for (open, close) in quotePairs {
            if s.count >= 2, s.first == open, s.last == close {
                s = String(s.dropFirst().dropLast()).trimmingCharacters(in: .whitespacesAndNewlines)
            }
        }

        return s
    }

    /// Translation-only cleanup on top of `sanitizeLLMOutput`.
    ///
    /// Asked to translate, a small on-device model frequently answers *about* the text
    /// ("This message is in Spanish and means 'hello'.") instead of returning the
    /// translation. `sanitizeLLMOutput` only knows a handful of "Here is the
    /// translation:" prefixes, so explanatory prose walked straight through it — which
    /// is exactly what users saw when tapping a message to translate.
    ///
    /// Returns nil when the answer is prose that cannot be reduced to a translation, so
    /// the caller falls back to the native iOS Translation sheet instead of displaying
    /// an explanation.
    private func sanitizeTranslation(_ raw: String, original: String) -> String? {
        var s = sanitizeLLMOutput(raw)
        guard !s.isEmpty else { return nil }

        // Explanatory openers the shared sanitizer does not cover.
        let explanatoryLeads: [String] = [
            "this message", "the message", "this text", "the text", "the original",
            "translated", "translation of", "it means", "this means", "that means",
            "it says", "this says", "in english", "in french", "in spanish",
            "le message", "ce message", "le texte", "la phrase", "cela signifie",
            "ça veut dire", "il s'agit", "en français", "en anglais",
            "este mensaje", "el mensaje", "significa",
            "diese nachricht", "die nachricht", "bedeutet",
            "questo messaggio", "il messaggio",
        ]
        let lower = s.lowercased()
        if explanatoryLeads.contains(where: { lower.hasPrefix($0) }) {
            // When a model explains, it almost always puts the actual translation in
            // quotes. Recover that, unless it is just the input echoed back.
            if let quoted = firstQuotedSpan(in: s),
               !quoted.isEmpty,
               quoted.compare(original, options: [.caseInsensitive, .diacriticInsensitive]) != .orderedSame {
                return quoted
            }
            return nil
        }

        // A translation is one message, never a multi-paragraph essay. If commentary was
        // appended after the translation, keep only the first paragraph.
        if let dblNL = s.range(of: "\n\n") {
            let head = String(s[..<dblNL.lowerBound]).trimmingCharacters(in: .whitespacesAndNewlines)
            if !head.isEmpty { s = head }
        }

        return s.isEmpty ? nil : s
    }

    /// First span wrapped in curly, guillemet or straight quotes.
    private func firstQuotedSpan(in text: String) -> String? {
        let pairs: [(Character, Character)] = [
            ("\u{201C}", "\u{201D}"), ("\u{00AB}", "\u{00BB}"), ("\"", "\""),
        ]
        for (open, close) in pairs {
            guard let start = text.firstIndex(of: open) else { continue }
            let after = text.index(after: start)
            guard after < text.endIndex,
                  let end = text[after...].firstIndex(of: close) else { continue }
            let span = String(text[after..<end]).trimmingCharacters(in: .whitespacesAndNewlines)
            if !span.isEmpty { return span }
        }
        return nil
    }

    /// True if the line looks like LLM meta-commentary, not a real suggestion.
    private func looksLikeMetaLine(_ line: String) -> Bool {
        let lower = line.lowercased().trimmingCharacters(in: .whitespacesAndNewlines)
        let metaPrefixes = [
            "okay,", "okay.", "ok,", "ok.", "sure,", "sure.", "of course,",
            "alright,", "got it,",
            "the user wants", "the user is asking",
            "let me ", "let's ", "i'll ", "i will ",
            "here's ", "here is ", "here are ",
            "first,", "second,", "third,",
            "voici ", "ecco ", "aquí ", "hier ",
        ]
        return metaPrefixes.contains(where: { lower.hasPrefix($0) })
    }

    /// Strip list bullets ("1.", "1)", "- ", "• ") AND caps-label prefixes
    /// ("WARM + SPECIFIC REACTION:", "REPLY 1:", "OPTION 1:") that the model leaks
    /// from the system prompt instead of cleanly outputting just the suggestion.
    private func stripListBullet(_ line: String) -> String {
        var s = line.trimmingCharacters(in: .whitespacesAndNewlines)
        let patterns = [
            "^\\s*\\d+\\.\\s+",
            "^\\s*\\d+\\)\\s+",
            "^\\s*[-•*]\\s+",
            // Caps-only label up to ~50 chars followed by colon + space, e.g. "WARM + SPECIFIC REACTION:"
            "^[A-Z][A-Z0-9 +/&_-]{2,48}:\\s+",
            // Reply-number prefix: "Reply 1:", "Option 2:", "Suggestion 3 -"
            "^(Reply|Option|Suggestion|Réponse|Proposition|Vorschlag|Sugerencia|Suggerimento|提案|답변)\\s*\\d+\\s*[:\\-–]\\s*",
        ]
        for p in patterns {
            s = s.replacingOccurrences(of: p, with: "", options: .regularExpression)
        }
        // Strip wrapping straight or curly quotes if the model wrapped each suggestion
        let pairs: [(Character, Character)] = [("\"", "\""), ("\u{201C}", "\u{201D}"), ("\u{00AB}", "\u{00BB}")]
        for (open, close) in pairs {
            if s.count >= 2, s.first == open, s.last == close {
                s = String(s.dropFirst().dropLast()).trimmingCharacters(in: .whitespacesAndNewlines)
            }
        }
        return s
    }

    /// Correct spelling and grammar using on-device LLM
    /// Works for all 16 OSHI languages: EN, FR, DE, ES, IT, PT-BR, PT-PT, JA, RU, PL, ZH, AR, HI, FA, HE, UK
    @available(iOS 26, *)
    func aiCorrect(_ text: String) async -> String {
        let lang = detectLanguage(text)
        let langName = lang.map { languageName(for: $0.rawValue) } ?? "the detected language"

        // Language-specific correction rules for the LLM
        let langSpecificRules: String
        switch lang {
        case .french:
            langSpecificRules = """
                French-specific rules: \
                - Fix missing accents (e, a, u, c cedilla, etc.) — e.g. "decontracte" → "décontracté". \
                - Add required spaces before ! ? ; : (French typography). \
                - Fix agreement errors (gender, number) — e.g. "elles sont partis" → "elles sont parties". \
                - Fix common mistakes: "sa" vs "ça", "a" vs "à", "ou" vs "où", "ce" vs "se", "et" vs "est". \
                - Fix subjunctive usage after "il faut que", "pour que", etc.
                """
        case .german:
            langSpecificRules = """
                German-specific rules: \
                - Capitalize all nouns (Substantive). \
                - Fix compound word spelling (Zusammenschreibung). \
                - Fix der/die/das article agreement. \
                - Fix Konjugation and verb placement (verb-second in main clauses, verb-final in subordinate clauses). \
                - Fix Umlaut usage (ä, ö, ü) and ß vs ss.
                """
        case .spanish:
            langSpecificRules = """
                Spanish-specific rules: \
                - Fix missing accents on stressed syllables (á, é, í, ó, ú). \
                - Fix inverted punctuation at sentence start (¿...? and ¡...!). \
                - Fix ser vs estar, por vs para usage. \
                - Fix subjunctive mood after expressions of doubt, desire, emotion. \
                - Fix gender/number agreement in adjectives and articles.
                """
        case .italian:
            langSpecificRules = """
                Italian-specific rules: \
                - Fix missing accents (è, é, à, ù, ò). \
                - Fix agreement between nouns and adjectives (gender + number). \
                - Fix use of "che" vs "cui" in relative clauses. \
                - Fix congiuntivo (subjunctive) after "che", "penso che", "credo che". \
                - Fix double consonants which change meaning.
                """
        case .russian:
            langSpecificRules = """
                Russian-specific rules: \
                - Fix word endings for grammatical cases (nominative, genitive, dative, accusative, instrumental, prepositional). \
                - Fix verb aspect usage (совершенный/несовершенный вид). \
                - Fix common mistakes: "тся" vs "ться", "не" vs "ни". \
                - Fix stress-dependent letter ё where it changes meaning.
                """
        case .japanese:
            langSpecificRules = """
                Japanese-specific rules: \
                - Fix particle usage: は vs が, に vs で, を correctly. \
                - Fix verb conjugation (て-form, ない-form, polite/casual). \
                - Fix keigo (敬語) levels when formal context detected. \
                - Fix kanji vs hiragana choice for common words. \
                - Fix sentence-ending particles (よ, ね, か) for natural flow.
                """
        case .simplifiedChinese:
            langSpecificRules = """
                Chinese-specific rules: \
                - Fix measure word (量词) usage with nouns. \
                - Fix 的/地/得 usage (attributive/adverbial/complement). \
                - Fix common character confusions (他/她/它, 在/再, 做/作). \
                - Use Chinese punctuation marks (，。！？、；：). \
                - Ensure natural sentence structure (Subject-Verb-Object).
                """
        case .arabic:
            langSpecificRules = """
                Arabic-specific rules: \
                - Fix hamza placement (أ, إ, ئ, ؤ, ء). \
                - Fix ta marbuta (ة) vs ha (ه) at word endings. \
                - Fix gender agreement between verbs, adjectives, and nouns. \
                - Fix alif maqsura (ى) vs ya (ي). \
                - Fix nunation (tanwin) where appropriate.
                """
        case .hebrew:
            langSpecificRules = """
                Hebrew-specific rules: \
                - Fix gender agreement (masculine/feminine) in verbs and adjectives. \
                - Fix definite article ה (ha) attachment. \
                - Fix common spelling variations and nikkud-less writing conventions. \
                - Fix verb binyan (conjugation pattern) consistency.
                """
        case .polish:
            langSpecificRules = """
                Polish-specific rules: \
                - Fix diacritics: ą, ę, ć, ł, ń, ó, ś, ź, ż. \
                - Fix noun declension (7 cases). \
                - Fix verb conjugation and aspect (dokonany/niedokonany). \
                - Fix common errors: "ó" vs "u", "rz" vs "ż", "ch" vs "h".
                """
        case .ukrainian:
            langSpecificRules = """
                Ukrainian-specific rules: \
                - Fix Ukrainian-specific letters: і, ї, є, ґ (not Russian и, е, г). \
                - Fix apostrophe usage (м'який знак vs апостроф). \
                - Fix case endings specific to Ukrainian grammar. \
                - Do NOT "correct" to Russian — preserve Ukrainian spelling.
                """
        case .hindi:
            langSpecificRules = """
                Hindi-specific rules: \
                - Fix Devanagari script errors and matras (vowel marks). \
                - Fix postposition usage (में, पर, को, से, के लिए). \
                - Fix gender agreement (masculine/feminine) in verbs and adjectives. \
                - Fix common Hinglish mixed words — keep as-is if intentional, correct if misspelled.
                """
        case .persian:
            langSpecificRules = """
                Farsi/Persian-specific rules: \
                - Fix Persian-specific characters (پ, چ, ژ, گ, ک, ی) — do not use Arabic equivalents. \
                - Fix ezafe (اضافه) construction. \
                - Fix verb conjugation (past, present, subjunctive stems). \
                - Fix spacing around the zero-width non-joiner (ZWNJ/نیم‌فاصله).
                """
        case .korean:
            langSpecificRules = """
                Korean-specific rules: \
                - Fix particle usage: 은/는 (topic), 이/가 (subject), 을/를 (object), 에/에서 (location). \
                - Fix honorific levels: 해요체 vs 합쇼체 vs 해체 — match formality to context. \
                - Fix spacing (띄어쓰기) — Korean compound words and particles follow strict spacing rules. \
                - Fix verb conjugation: stem + ending agreement (ㄹ irregular, ㅂ irregular, ㅎ irregular). \
                - Fix common confusions: 되/돼, 데/대, 로서/로써, 에/에게. \
                - Fix Sino-Korean vs native Korean number usage (일/이/삼 vs 하나/둘/셋 with appropriate counters).
                """
        case .portuguese:
            langSpecificRules = """
                Portuguese-specific rules: \
                - Fix missing accents and diacritics (á, é, í, ó, ú, â, ê, ô, ã, õ, ç). \
                - Fix verb conjugation across all tenses (present, preterite, imperfect, future, subjunctive). \
                - Fix "ser" vs "estar" usage, "por" vs "para", "a" vs "à" (crase). \
                - Fix gender/number agreement in articles, adjectives, and past participles. \
                - Handle both Brazilian Portuguese (PT-BR: você, gerund "-ando/-endo/-indo") and European Portuguese (PT-PT: tu, infinitive constructions "a + infinitive"). \
                - Fix common errors: "mais" vs "mas", "há" vs "a" (time expressions), "mau" vs "mal". \
                - Fix pronoun placement (enclisis, proclisis, mesoclisis rules).
                """
        default:
            langSpecificRules = ""
        }

        let session = LanguageModelSession(instructions: """
            You are an expert spelling, grammar, and punctuation correction assistant. \
            The user's text is in \(langName). \
            \
            Your job: \
            1. Fix ALL spelling mistakes, typos, and misspelled words. \
            2. Fix ALL grammar errors (verb conjugation, agreement, tense, case endings). \
            3. Fix punctuation (missing periods, commas, question marks, exclamation marks). \
            4. Fix capitalization (start of sentences, proper nouns). \
            5. Fix accents and diacritics that are missing or wrong. \
            \
            \(langSpecificRules) \
            \
            CRITICAL RULES: \
            - Keep the EXACT same language — do NOT translate to another language. \
            - Keep the SAME meaning and tone — do NOT rephrase or rewrite. \
            - Keep informal/casual style if the original is casual — just fix errors. \
            - If the text has no errors, return it unchanged. \
            - Return ONLY the corrected text. No explanation, no quotes, no prefix.
            """)

        do {
            let response = try await session.respond(to: text)
            return sanitizeLLMOutput(response.content)
        } catch {
            return autoCorrect(text)
        }
    }

    /// Improve message with a specific tone using on-device LLM
    /// Works for all 16 OSHI languages with context-aware reformulation
    @available(iOS 26, *)
    func aiImprove(_ text: String, style: ImprovementStyle, replyContext: String? = nil) async -> String {
        let lang = detectLanguage(text)
        let langName = lang.map { languageName(for: $0.rawValue) } ?? "the detected language"

        let styleInstruction: String
        switch style {
        case .formal:
            styleInstruction = """
                TONE: Formal, elegant, distinguished. \
                \
                YOUR JOB: Completely rewrite the message as if a polished, well-educated person were expressing the same idea. \
                Change sentence structure, vocabulary, and rhythm. DO NOT just add "please" or remove contractions — REIMAGINE the message. \
                \
                LANGUAGE-SPECIFIC FORMAL STYLE: \
                - FR: Use "vous", subjunctive where appropriate, literary vocabulary. "J'aimerais qu'on se voie" → "Il me serait agréable de convenir d'un rendez-vous à votre meilleure convenance." \
                - DE: Use "Sie", Konjunktiv II for politeness, compound nouns. "Können wir reden?" → "Ich würde mich freuen, wenn Sie Zeit für ein Gespräch fänden." \
                - IT: Use "Lei", congiuntivo, formal register. "Ci vediamo domani?" → "Le sarei grato se potessimo fissare un incontro per domani." \
                - ES: Use "usted", subjunctive, formal openings. "¿Podemos hablar?" → "Sería un placer poder conversar con usted cuando le resulte oportuno." \
                - JA: Use 敬語 (keigo) — 尊敬語 and 謙譲語. "明日会える？" → "明日お目にかかることは可能でございましょうか。" \
                - KO: Use 합쇼체 (formal polite). "내일 만날 수 있어?" → "내일 뵙는 것이 가능하시겠습니까?" \
                - PT: Use "o senhor/a senhora". "Podemos conversar?" → "Seria possível agendarmos uma conversa no momento que lhe for mais conveniente?" \
