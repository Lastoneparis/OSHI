    // MARK: - Post-Dictation Auto-Correct

    /// Auto-correct text after voice dictation. Returns (corrected text, was changed).
    func autoCorrectionAfterDictation(_ text: String) async -> (text: String, wasChanged: Bool) {
        let corrected = await processCorrection(text)
        let changed = corrected != text
        return (corrected, changed)
    }

    // MARK: - Unified Processing Entry Points

    /// Process correction: uses Foundation Models on iOS 26+, local LLM fallback, then rule-based
    func processCorrection(_ text: String) async -> String {
        if Task.isCancelled { return text }
        #if canImport(FoundationModels)
        if #available(iOS 26, *), SystemLanguageModel.default.isAvailable {
            return await aiCorrect(text)
        }
        #endif
        // Local LLM fallback
        if LocalLLMManager.shared.isModelDownloaded {
            let prompt = "Fix all spelling, grammar, and punctuation errors in the following text. Return ONLY the corrected text, nothing else. If the text has no errors, return it unchanged.\n\nText: \(text)"
            let result = await LocalLLMManager.shared.generate(prompt: prompt)
            if Task.isCancelled { return text }
            if !result.isEmpty && !result.contains("not yet linked") {
                return result
            }
        }
        return autoCorrect(text)
    }

    /// Process improvement: uses Foundation Models on iOS 26+, local LLM fallback, then rule-based
    func processImprovement(_ text: String, style: ImprovementStyle, replyContext: String? = nil) async -> String {
        if Task.isCancelled { return text }
        #if canImport(FoundationModels)
        if #available(iOS 26, *), SystemLanguageModel.default.isAvailable {
            return await aiImprove(text, style: style, replyContext: replyContext)
        }
        #endif
        // Local LLM fallback
        if LocalLLMManager.shared.isModelDownloaded {
            let styleDesc: String
            switch style {
            case .formal: styleDesc = "formal and elegant"
            case .casual: styleDesc = "casual and relaxed, like texting a friend"
            case .friendly: styleDesc = "warm and friendly"
            case .professional: styleDesc = "professional and business-appropriate"
            case .playful: styleDesc = "playful and fun"
            case .persuasive: styleDesc = "persuasive and convincing"
            case .flirty: styleDesc = "charming and flirty"
            case .seductive: styleDesc = "alluring and magnetic"
            case .intrigued: styleDesc = "curious and fascinated"
            }
            var prompt = "Rewrite this message in a \(styleDesc) tone. Keep the same language and meaning. Return ONLY the rewritten message.\n\n"
            if let ctx = replyContext, !ctx.isEmpty {
                prompt += "Conversation context:\n\(String(ctx.prefix(400)))\n\n"
            }
            prompt += "Message: \(text)"
            let result = await LocalLLMManager.shared.generate(prompt: prompt)
            if Task.isCancelled { return text }
            if !result.isEmpty && !result.contains("not yet linked") {
                return result
            }
        }
        return improveMessageRuleBased(text, style: style)
    }

    /// Process translation: uses Foundation Models on iOS 26+, local LLM fallback
    func processTranslation(_ text: String, to targetLanguage: String) async -> String? {
        #if canImport(FoundationModels)
        if #available(iOS 26, *), SystemLanguageModel.default.isAvailable {
            return await aiTranslate(text, to: targetLanguage)
        }
        #endif
        // Local LLM fallback
        if LocalLLMManager.shared.isModelDownloaded {
            let targetName = languageName(for: targetLanguage)
            let prompt = "Translate the following text into \(targetName). Return ONLY the translated text.\n\nText: \(text)"
            let result = await LocalLLMManager.shared.generate(prompt: prompt)
            if !result.isEmpty && !result.contains("not yet linked") {
                // Unlike processAskAI, a translation MUST be sanitized. LocalLLMManager's
                // post-process only strips ChatML / <think> / junk lines — it has no notion
                // of "Here is the translation:" or of a model that explains instead of
                // translating. The Foundation Models path already calls sanitizeLLMOutput;
                // this fallback did not, which is why the local LLM returned prose.
                if let cleaned = sanitizeTranslation(result, original: text) {
                    return cleaned
                }
                // Unrecoverable prose: fall through to nil so the caller opens the
                // native iOS Translation sheet instead of showing an explanation.
            }
        }
        return nil // Caller should show iOS Translation sheet or unavailable message
    }

