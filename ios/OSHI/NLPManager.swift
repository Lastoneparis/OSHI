    /// Ask AI a simple question and get an answer using on-device LLM
    @available(iOS 26, *)
    func aiAsk(_ question: String, conversationContext: String? = nil) async -> String {
        // Same SHORT system prompt as Android Qwen path. Heavy instructions confuse the
        // model and produce verbose / markdown / code-block answers. Sanitizer handles the rest.
        let contextLine: String
        if let ctx = conversationContext, !ctx.isEmpty {
            contextLine = "Conversation context:\n\(String(ctx.prefix(600)))\n\n"
        } else {
            contextLine = ""
        }
        let session = LanguageModelSession(instructions: """
            You are OSHI, a helpful and privacy-focused AI assistant. \
            Give clear, accurate, concise answers in 1-3 sentences. \
            Respond in the same language the user writes in. \
            Answer directly — do not greet, do not restate the question, never speak as the user. \
            Only produce code when the user explicitly asks for code — never answer a factual question with a code block.
            """)

        do {
            let response = try await session.respond(to: contextLine + question)
            return sanitizeLLMOutput(response.content)
        } catch {
            return "ai.ask_unavailable".localized
        }
    }

