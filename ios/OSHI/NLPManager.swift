            let prompt = "Write a short 'thinking of you' message to \(recipientName) in a \(toneDesc) tone. Keep it to 1-2 sentences. Return ONLY the message.\n\nContext:\n\(String(conversationContext.prefix(300)))"
            let result = await LocalLLMManager.shared.generate(prompt: prompt)
            if !result.isEmpty && !result.contains("not yet linked") {
                return (result, true)
            }
        }
        // Template fallback — uses conversation language, not device language
        return (generateThinkingOfYouTemplate(recipientName: recipientName, tone: tone, timeOfDay: timeOfDay, conversationLanguage: conversationLang), false)
    }

