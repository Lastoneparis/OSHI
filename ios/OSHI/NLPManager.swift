    /// Detect conversation language from recent messages context
    private func detectConversationLanguage(from context: String) -> String {
        guard !context.isEmpty else {
            return Locale.current.language.languageCode?.identifier ?? "en"
        }
        let recognizer = NLLanguageRecognizer()
        recognizer.processString(context)
        return recognizer.dominantLanguage?.rawValue ?? Locale.current.language.languageCode?.identifier ?? "en"
    }

