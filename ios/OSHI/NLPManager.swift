    // MARK: - Processing

    private func processAction(_ action: AIAction) {
        let text = messageText.trimmingCharacters(in: .whitespacesAndNewlines)
        // Allow .generate and .ask to work with empty text (generating from scratch)
        guard !text.isEmpty || action == .generate || action == .ask else { return }

        switch action {
        case .correct:
            runAsync { await nlpManager.processCorrection(text) }
        case .improve:
            runAsync { await nlpManager.processImprovement(text, style: .casual, replyContext: replyingToMessage) }
        case .translate:
            if usesFoundationModel {
                correctedText = ""
            } else {
                if #available(iOS 18.0, *) {
                    showTranslation = true
                    correctedText = text
                } else {
                    correctedText = "ai.translate_unavailable".localized
                }
            }
        case .tone:
            processStyle(selectedStyle)
        case .generate:
            currentAITask?.cancel()
            correctedText = ""
            // Trigger initial generation
            isLoading = true
            let mode = selectedGeneratorMode
            let ctx = replyingToMessage
            currentAITask = Task {
                await nlpManager.generateConversationSuggestions(
                    mode: mode,
                    conversationContext: ctx,
                    recipientName: nil
                )
                if Task.isCancelled { return }
                let suggestions = nlpManager.conversationSuggestions
                if !suggestions.isEmpty {
                    correctedText = suggestions.enumerated().map { (i, s) in
                        "\(i + 1). \(s)"
                    }.joined(separator: "\n\n")
                }
                isLoading = false
                currentAITask = nil
            }
        case .ask:
            correctedText = ""
        }
    }

    private func processStyle(_ style: NLPManager.ImprovementStyle) {
        let text = messageText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        runAsync { await nlpManager.processImprovement(text, style: style, replyContext: replyingToMessage) }
    }

    private func processTranslation(to targetLanguage: String) {
        let text = messageText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        runAsync {
            if let translated = await nlpManager.processTranslation(text, to: targetLanguage) {
                return translated
            }
            return text
        }
    }

    private func runAsync(_ operation: @escaping () async -> String) {
        // Cancel any previous in-flight AI task before starting a new one
        currentAITask?.cancel()
        isLoading = true
        correctedText = ""
        // Cancellable Task — the LLM context itself is an `actor` so heavy
        // work already runs off the MainActor. We add cooperative cancellation
        // so the user can abort via the Cancel button in the loading indicator.
        currentAITask = Task {
            let result = await operation()
            if Task.isCancelled { return }
            withAnimation(.easeInOut(duration: 0.3)) {
                correctedText = result
                isLoading = false
            }
            currentAITask = nil
        }
    }

    private func iconForAction(_ action: AIAction) -> String {
        switch action {
        case .correct: return "textformat.abc"
        case .improve: return "wand.and.stars"
        case .translate: return "globe"
        case .tone: return "theatermasks.fill"
        case .generate: return "sparkle.magnifyingglass"
        case .ask: return "bubble.left.and.text.bubble.right.fill"
        }
    }
