// MARK: - Translation Modifier (iOS 18+)

extension View {
    @ViewBuilder
    func if_available_translation(sourceText: String, isPresented: Binding<Bool>) -> some View {
        if #available(iOS 18.0, *) {
            self.modifier(TranslationModifier(sourceText: sourceText, isPresented: isPresented))
        } else {
            self
        }
    }
}

@available(iOS 18.0, *)
struct TranslationModifier: ViewModifier {
    let sourceText: String
    @Binding var isPresented: Bool

    func body(content: Content) -> some View {
        // __CATALYST_SPIKE_2026_06_20__ .translationPresentation is unavailable on
        // Mac Catalyst — skip it there (the system Translate sheet isn't on Mac anyway).
        #if targetEnvironment(macCatalyst)
        content
        #else
        content
            .translationPresentation(isPresented: $isPresented, text: sourceText)
        #endif
    }
}

// MARK: - Compact AI Toolbar (inline above keyboard)

struct AIQuickBar: View {
    @Binding var messageText: String
    /// Recent conversation messages for context-aware AI actions (last 5 messages as "You: ..." / "Them: ...")
    var conversationContext: String = ""
    @State private var showAISheet = false

    // Cancellable AI task tracking so the user can abort long generation
    @State private var aiTask: Task<Void, Never>? = nil
    @State private var isAIBusy: Bool = false
    @State private var originalTextBeforeAI: String = ""

    private let brandColor = Theme.brand
    private let accentPink = Color(red: 0.94, green: 0.28, blue: 0.56)

    var body: some View {
        HStack(spacing: 8) {
            if isAIBusy {
                // Inline progress + cancel button while AI is generating
                HStack(spacing: 6) {
                    ProgressView()
                        .controlSize(.small)
                        .tint(brandColor)
                    Text("ai.processing".localized)
                        .font(.caption2.weight(.medium))
                        .foregroundColor(.secondary)
                }
                .padding(.horizontal, 10)
                .padding(.vertical, 6)
                .background(Color(.tertiarySystemGroupedBackground))
                .cornerRadius(14)

                Button {
                    cancelAIAndRestore()
                } label: {
                    HStack(spacing: 4) {
                        Image(systemName: "xmark.circle.fill")
                            .font(.caption)
                        Text("common.cancel".localized)
                            .font(.caption2.weight(.semibold))
                    }
                    .padding(.horizontal, 10)
                    .padding(.vertical, 6)
                    .background(Color.red.opacity(0.12))
                    .foregroundColor(.red)
                    .cornerRadius(14)
                }
                .accessibilityLabel(Text("common.cancel".localized))

                Spacer(minLength: 0)
            } else {
                // Quick spell check
                Button {
                    runAICorrection()
                } label: {
                    Label("ai.quick.correct".localized, systemImage: "textformat.abc")
                        .font(.caption2.weight(.medium))
                        .padding(.horizontal, 10)
                        .padding(.vertical, 6)
                        .background(Color(.tertiarySystemGroupedBackground))
                        .cornerRadius(14)
                }
                .disabled(isAIBusy)

                // Quick improve — uses conversation context for better rewrites
                Button {
                    runAIImprovement()
                } label: {
                    HStack(spacing: 3) {
                        aiBadgeMini
                        Text("ai.quick.improve".localized)
                    }
                    .font(.caption2.weight(.medium))
                    .padding(.horizontal, 10)
                    .padding(.vertical, 6)
                    .background(Color(.tertiarySystemGroupedBackground))
                    .cornerRadius(14)
                }
                .disabled(isAIBusy)

                // Full AI sheet
                Button {
                    showAISheet = true
                } label: {
                    HStack(spacing: 3) {
                        aiBadgeMini
                        Image(systemName: "ellipsis")
                            .font(.caption2)
                    }
                    .padding(.horizontal, 8)
                    .padding(.vertical, 6)
                    .background(
                        LinearGradient(colors: [brandColor.opacity(0.12), accentPink.opacity(0.08)], startPoint: .leading, endPoint: .trailing)
                    )
                    .foregroundColor(brandColor)
                    .cornerRadius(14)
                }
                .disabled(isAIBusy)
            }
        }
        .sheet(isPresented: $showAISheet) {
            AIShortcutsView(messageText: $messageText, isPresented: $showAISheet)
                .presentationDetents([.medium, .large])
        }
        .onDisappear {
            // Abort any in-flight work if the user leaves the chat
            aiTask?.cancel()
            aiTask = nil
            isAIBusy = false
        }
    }

    // MARK: - AI task runners (cancellable, off the main actor)

    private func runAICorrection() {
        guard !isAIBusy else { return }
        let text = messageText
        originalTextBeforeAI = text
        isAIBusy = true
        // Cancellable Task. The underlying LlamaContext is an `actor`, so token
        // generation already runs off the MainActor; we just need cooperative
        // cancellation and a way to reach into the task from the Cancel button.
        aiTask = Task {
            let result = await NLPManager.shared.processCorrection(text)
            if Task.isCancelled { return }
            messageText = result
            isAIBusy = false
            aiTask = nil
        }
    }

    private func runAIImprovement() {
        guard !isAIBusy else { return }
        let text = messageText
        let ctx = conversationContext
        originalTextBeforeAI = text
        isAIBusy = true
        aiTask = Task {
            let result = await NLPManager.shared.processImprovement(text, style: .casual, replyContext: ctx)
            if Task.isCancelled { return }
            messageText = result
            isAIBusy = false
            aiTask = nil
        }
    }

    private func cancelAIAndRestore() {
        aiTask?.cancel()
        aiTask = nil
        // Restore the user's original text — never leave them with a partial rewrite
        messageText = originalTextBeforeAI
        isAIBusy = false
        // Haptic feedback to confirm cancellation
        let generator = UINotificationFeedbackGenerator()
        generator.notificationOccurred(.warning)
    }

    private var aiBadgeMini: some View {
        Text("AI")
            .font(.scaled(7, weight: .black, design: .rounded))
            .foregroundColor(.white)
            .padding(.horizontal, 3)
            .padding(.vertical, 1)
            .background(
                LinearGradient(colors: [brandColor, accentPink], startPoint: .leading, endPoint: .trailing)
            )
            .cornerRadius(3)
    }
}

