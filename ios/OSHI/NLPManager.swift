    /// Detect the dominant language of a text.
    ///
    /// Adds two biases that NLLanguageRecognizer doesn't apply by default and
    /// that matter a lot in chat: (1) the device's UI language and (2) the
    /// last language we successfully detected for this user. Without hints,
    /// short messages like "ok", "non", "ja" get mis-classified into random
    /// languages (Norwegian, Croatian, etc.) and the smart-reply prompt then
    /// asks the LLM to write back in the wrong language.
    /// __AI_SPEAKS_THE_USER_NOT_THE_UI_2026_10_17__ The language the assistant
    /// should WRITE in, which is not the language the app is drawn in.
    ///
    /// Every site here used `Locale.current`, i.e. the app's resolved locale.
    /// That is correct for buttons and wrong for generated text as soon as
    /// someone uses macOS's per-app language override (System Settings →
    /// General → Language & Region → Applications): a French user who pins
    /// OSHI's interface to English then gets translations and smart replies in
    /// ENGLISH, because the app's locale says "en" while the person speaks
    /// French. Measured on this Mac — `Moriceau-lab.Genesis AppleLanguages` is
    /// `(en)` while the account's language is French.
    ///
    /// So the OUTPUT language follows the system's preferred language, and
    /// falls back to the app locale when that cannot be read (a sandbox without
    /// access to `.GlobalPreferences` — never a crash, just today's behaviour).
    static var contentLanguageCode: String {
        if let sys = UserDefaults(suiteName: ".GlobalPreferences")?
            .stringArray(forKey: "AppleLanguages")?.first,
           let code = Locale(identifier: sys).language.languageCode?.identifier,
           !code.isEmpty {
            return code
        }
        return Locale.current.language.languageCode?.identifier ?? "en"
    }

    @discardableResult
    func detectLanguage(_ text: String) -> NLLanguage? {
        let recognizer = NLLanguageRecognizer()
        var hints: [NLLanguage: Double] = [:]
        if let deviceCode = Locale.current.language.languageCode?.identifier {
            hints[NLLanguage(rawValue: deviceCode)] = 0.5
        }
        let prev = self.detectedLanguage
        if !prev.isEmpty {
            // Slight preference for sticking with the conversation's
            // previously-detected language unless evidence is strong.
            hints[NLLanguage(rawValue: prev), default: 0] += 0.3
        }
        if !hints.isEmpty {
            recognizer.languageHints = hints
        }
        recognizer.processString(text)
        if let lang = recognizer.dominantLanguage {
            self.detectedLanguage = lang.rawValue
            return lang
        }
        return nil
    }

    /// Get language name from code
    func languageName(for code: String) -> String {
        Locale.current.localizedString(forLanguageCode: code)
            ?? Locale(identifier: code).localizedString(forLanguageCode: code)
            ?? code
    }

    // MARK: - Spell Check (Rule-Based Fallback)

    struct SpellSuggestion: Identifiable {
        let id = UUID()
        let range: NSRange
        let word: String
        let suggestions: [String]
    }

    /// Check spelling of text and return misspelled words with suggestions
    func checkSpelling(_ text: String, language: String? = nil) -> [SpellSuggestion] {
        let lang = language ?? detectedLanguage
        let nsText = text as NSString
        var results: [SpellSuggestion] = []
        var searchRange = NSRange(location: 0, length: nsText.length)

        while searchRange.location < nsText.length {
            let misspelledRange = textChecker.rangeOfMisspelledWord(
                in: text,
                range: NSRange(location: 0, length: nsText.length),
                startingAt: searchRange.location,
                wrap: false,
                language: lang
            )

            if misspelledRange.location == NSNotFound { break }

            let word = nsText.substring(with: misspelledRange)
            let guesses = textChecker.guesses(
                forWordRange: misspelledRange,
                in: text,
                language: lang
            ) ?? []

            results.append(SpellSuggestion(
                range: misspelledRange,
                word: word,
                suggestions: Array(guesses.prefix(5))
            ))

            searchRange.location = misspelledRange.location + misspelledRange.length
        }

        self.spellSuggestions = results
        return results
    }

    /// Auto-correct text: fix spelling, grammar, punctuation, and capitalization
    /// Works in any language — auto-detects the message language first
    func autoCorrect(_ text: String, language: String? = nil) -> String {
        // 1. Detect language if not provided
        let lang = language ?? {
            let detected = detectLanguage(text)
            return detected?.rawValue ?? "en"
        }()

        // 2. Fix spelling using system spell checker (works for all iOS-supported languages)
        let errors = checkSpelling(text, language: lang)
        var corrected = text
        for error in errors.reversed() {
            if let firstSuggestion = error.suggestions.first,
               let range = Range(error.range, in: corrected) {
                corrected.replaceSubrange(range, with: firstSuggestion)
            }
        }

        // 3. Fix grammar patterns (language-agnostic)
        corrected = fixDoubleSpaces(corrected)
        corrected = capitalizeFirstLetter(corrected)
        corrected = fixCapitalizationAfterPunctuation(corrected)

        // 4. Fix common French-specific grammar issues
        if lang == "fr" || NLLanguage(rawValue: lang) == .french {
            corrected = fixFrenchGrammar(corrected)
        }

        return corrected
    }

    /// Fix capitalization after sentence-ending punctuation
    private func fixCapitalizationAfterPunctuation(_ text: String) -> String {
        var result = ""
        var capitalizeNext = false
        for char in text {
            if capitalizeNext && char.isLetter {
                result.append(char.uppercased())
                capitalizeNext = false
            } else if capitalizeNext && char == " " {
                result.append(char)
            } else {
                if capitalizeNext { capitalizeNext = false }
                result.append(char)
            }
            if char == "." || char == "!" || char == "?" {
                capitalizeNext = true
            }
        }
        return result
    }

    /// Fix common French grammar patterns
    private func fixFrenchGrammar(_ text: String) -> String {
        var result = text
        // Fix missing spaces before French punctuation (! ? ; :)
        let frPunctuation: [(String, String)] = [
            ("([^ ])!", "$1 !"), ("([^ ])\\?", "$1 ?"),
            ("([^ ]);", "$1 ;"), ("([^ ]):", "$1 :"),
        ]
        for (pattern, replacement) in frPunctuation {
            if let regex = try? NSRegularExpression(pattern: pattern) {
                result = regex.stringByReplacingMatches(in: result, range: NSRange(result.startIndex..., in: result), withTemplate: replacement)
            }
        }
        // Fix common accent mistakes
        let accentFixes: [(String, String)] = [
            (" a le ", " au "), (" a les ", " aux "),
            (" de le ", " du "), (" de les ", " des "),
        ]
        for (wrong, right) in accentFixes {
            result = result.replacingOccurrences(of: wrong, with: right, options: .caseInsensitive)
        }
        return result
    }

    // MARK: - Sentiment Analysis

    enum Sentiment: String {
        case positive, neutral, negative
    }

    func analyzeSentiment(_ text: String) -> (sentiment: Sentiment, score: Double) {
        let tagger = NLTagger(tagSchemes: [.sentimentScore])
        tagger.string = text
        let (tag, _) = tagger.tag(at: text.startIndex, unit: .paragraph, scheme: .sentimentScore)
        let score = Double(tag?.rawValue ?? "0") ?? 0.0

        let sentiment: Sentiment
        if score > 0.1 {
            sentiment = .positive
        } else if score < -0.1 {
            sentiment = .negative
        } else {
            sentiment = .neutral
        }
        return (sentiment, score)
    }

