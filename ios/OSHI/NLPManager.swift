    /// Ask AI a question: uses Foundation Models on iOS 26+, local LLM fallback.
    /// `conversationContext` lets the assistant resolve pronouns and follow-ups
    /// ("what about that?") — pass the last few messages of the active chat.
    func processAskAI(_ question: String, conversationContext: String? = nil) async -> String? {
        #if canImport(FoundationModels)
        if #available(iOS 26, *), SystemLanguageModel.default.isAvailable {
            return await aiAsk(question, conversationContext: conversationContext)
        }
        #endif
        // Local LLM fallback — exact same shape as Android `processAskAI`. LocalLLMManager
        // already strips ChatML tokens / <think> blocks / hallucinated code / leading noise /
        // role preamble in its 5-stage post-process. Running NLPManager.sanitizeLLMOutput on
        // top of that double-sanitizes and was occasionally eating valid answers. Trust the
        // LocalLLMManager output — same as Android does.
        if LocalLLMManager.shared.isModelDownloaded {
            let ctxBlock = conversationContext.flatMap { ctx in ctx.isEmpty ? nil : "Context:\n\(String(ctx.prefix(800)))\n\n" } ?? ""
            let prompt = "\(ctxBlock)\(question)"
            let result = await LocalLLMManager.shared.generate(prompt: prompt)
            if !result.isEmpty && !result.contains("not yet linked") {
                return result
            }
        }
        return nil
    }

    /// Translate received message to device language
    func processTranslateReceived(_ text: String) async -> String? {
        #if canImport(FoundationModels)
        if #available(iOS 26, *), SystemLanguageModel.default.isAvailable {
            return await aiTranslateToDeviceLanguage(text)
        }
        #endif
        // Local LLM fallback
        if LocalLLMManager.shared.isModelDownloaded {
            let deviceLang = Locale.current.language.languageCode?.identifier ?? "en"
            let deviceLangName = languageName(for: deviceLang)
            let prompt = "Translate the following message into \(deviceLangName). Return ONLY the translated text.\n\nMessage: \(text)"
            let result = await LocalLLMManager.shared.generate(prompt: prompt)
            if !result.isEmpty && !result.contains("not yet linked") {
                // See processTranslation: the local LLM path must sanitize too.
                if let cleaned = sanitizeTranslation(result, original: text) {
                    return cleaned
                }
                // Unrecoverable prose: fall through to the native Translation sheet.
            }
        }
        return nil // Caller should use iOS Translation sheet fallback
    }

    // MARK: - Rule-Based Improvement (Fallback)

    /// Improve message: fix spelling + basic grammar + punctuation (rule-based)
    func improveMessageRuleBased(_ text: String, style: ImprovementStyle = .casual, language: String? = nil) -> String {
        var improved = autoCorrect(text, language: language)

        // Basic improvements
        improved = capitalizeFirstLetter(improved)
        improved = fixDoubleSpaces(improved)
        improved = ensurePunctuation(improved)

        // Style adjustments
        switch style {
        case .formal:
            improved = makeFormal(improved)
        case .casual:
            improved = makeCasual(improved)
        case .friendly:
            improved = makeFriendly(improved)
        case .professional:
            improved = makeProfessional(improved)
        case .playful:
            improved = makePlayful(improved)
        case .persuasive:
            improved = makePersuasive(improved)
        case .flirty:
            improved = makeFlirty(improved)
        case .seductive:
            improved = makeSeductive(improved)
        case .intrigued:
            improved = makeIntrigued(improved)
        }

        return improved
    }

    // MARK: - Text Utilities (Rule-Based)

    private func capitalizeFirstLetter(_ text: String) -> String {
        guard !text.isEmpty else { return text }
        var result = ""
        var capitalizeNext = true
        for char in text {
            if capitalizeNext && char.isLetter {
                result.append(char.uppercased())
                capitalizeNext = false
            } else {
                result.append(char)
            }
            if char == "." || char == "!" || char == "?" {
                capitalizeNext = true
            }
        }
        return result
    }

    private func fixDoubleSpaces(_ text: String) -> String {
        var result = text
        while result.contains("  ") {
            result = result.replacingOccurrences(of: "  ", with: " ")
        }
        return result
    }

    private func ensurePunctuation(_ text: String) -> String {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return text }
        let lastChar = trimmed.last!
        if !lastChar.isPunctuation && trimmed.count > 3 {
            return trimmed + "."
        }
        return trimmed
    }

